/**
 * Mock peer plans — activities hosted by peers rather than venues. Two
 * flavors, same shape:
 *
 *  - linked plans: referenced from a venue event's `peerPlanIds` and listed in
 *    the "Going together" menu of that event's activity card.
 *  - standalone plans: not tied to a venue event; they appear on the map as
 *    peer pins (see MapHome `pins`) and open the peer activity card directly.
 *
 * Purely a visual prototype: joining goes nowhere yet.
 */
export type PeerPlan = {
  id: string;
  title: string;
  /** First name of the peer hosting it — "Theo - 3 going" on list rows. */
  host: string;
  /** Sub-line under the host name on the card ("Erasmus - from Lyon"). */
  hostLine: string;
  address: string;
  /** Display time ("Today - 20:30"). */
  when: string;
  description: string;
  /** The two featured names on the card ("Giulia, Martin"). */
  goingNames: string;
  /** Everyone going (drives "N going" rows and "+N others"). */
  goingCount: number;
};

/** "+N others are going" under the featured names. */
export const planOthers = (p: PeerPlan) => Math.max(0, p.goingCount - 2);

// Compact builder, purely to keep the entries below one-liners.
function plan(
  id: string,
  title: string,
  host: string,
  hostLine: string,
  when: string,
  address: string,
  description: string,
  goingNames: string,
  goingCount: number,
): PeerPlan {
  return {
    id,
    title,
    host,
    hostLine,
    address,
    when,
    description,
    goingNames,
    goingCount,
  };
}

